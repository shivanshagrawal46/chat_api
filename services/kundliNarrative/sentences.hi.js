W.glance = (f) => {
    const seed = `glance:${f.lagna}:${f.moonSign}`;
    const sign = D.SIGNS[f.lagna];
    const el = D.ELEMENTS[sign.element];
    const q = D.QUALITIES[sign.quality];
    const whose = f.name ? `${f.name} की` : 'आपकी';

    const p1 = `यह विश्लेषण ${whose} जन्म-कुंडली पर आधारित है, जिसका लग्न ${S(f.lagna)} है और लग्नेश ${P(f.lagnaLord)} हैं। ${S(f.lagna)} लग्न आपको ${sign.persona.hi} बनाता है। यह ${el.hi} की ${q.hi} राशि है, जो आपके मूल स्वभाव में ${el.trait.hi} लाती है, और ${q.trait.hi}।`;

    const parts2 = [];
    if (f.moonSign) parts2.push(`आपका चंद्रमा ${S(f.moonSign)} राशि में है, इसलिए आपका भावनात्मक मन ${D.SIGNS[f.moonSign].persona.hi} है; यही राशि आपकी मनोदशा, सहज-प्रवृत्तियों और सुरक्षा की भावना को नियंत्रित करती है।`);
    if (f.nakshatra) {
        parts2.push(`आपका जन्म-नक्षत्र ${f.nakshatra} है${f.nakshatraLordHi ? `, जिसके स्वामी ${f.nakshatraLordHi} हैं` : ''}।`);
        if (f.nakshatraLordHi) parts2.push('जन्म-नक्षत्र का स्वामी आपकी पहली महादशा का स्वर तय करता है और जब भी उसकी दशा चलती है, एक आवर्ती विषय के रूप में लौटता है।');
    }
    if (f.mangalDosh === true) parts2.push('कुंडली में मंगल दोष भी दिखाई देता है, जिसकी चर्चा विवाह खंड में आगे की गई है।');
    const p2 = parts2.length ? parts2.join(' ') : 'गणना से चंद्र राशि और जन्म-नक्षत्र उपलब्ध नहीं हो सके, इसलिए यह विश्लेषण लग्न और ग्रहों के भावों पर आधारित है।';

    let shape;
    if (f.kendraCount + f.trikonaCount >= 5) shape = 'ग्रहों का एक बड़ा हिस्सा केंद्र और त्रिकोण भावों में है, जो कुंडली की सबसे मज़बूत स्थितियाँ हैं, और इससे कुंडली को एक ठोस, सुदृढ़ आधार मिलता है';
    else if (f.dusthanaCount >= 4) shape = 'कई ग्रह कठिन षष्ठ, अष्टम और द्वादश भावों में हैं, जिससे यह ऐसी कुंडली बनती है जो सहज सौभाग्य के बजाय संघर्ष, सेवा और आंतरिक रूपांतरण से आगे बढ़ती है';
    else shape = 'ग्रह मज़बूत, वृद्धिशील और चुनौतीपूर्ण भावों में लगभग समान रूप से बँटे हुए हैं, जिससे एक संतुलित कुंडली बनती है जहाँ सही दिशा में किया गया प्रयास फल देता है';
    const n = f.planetsInH1.length;
    const p3 = `कुंडली को समग्र रूप से देखें तो ${shape}। ${n ? `${joinList(f.planetsInH1.map(P), L)} लग्न के साथ उदित ${many(n, 'हैं', 'है')} और आपके व्यक्तित्व में ${many(n, 'इनकी', 'इसकी')} सीधी भूमिका है।` : 'लग्न के साथ कोई ग्रह उदित नहीं है, इसलिए आपका व्यक्तित्व मुख्यतः लग्न राशि और उसके स्वामी के माध्यम से व्यक्त होता है।'} ${pick(['नीचे के खंड जीवन के प्रत्येक क्षेत्र को क्रम से लेते हैं, जिसकी शुरुआत स्वयं लग्न से होती है।', 'जीवन के प्रत्येक क्षेत्र की समीक्षा नीचे की गई है, जिसका आरंभ लग्न और लग्नेश से होता है।'], seed)}`;

    return [p1, p2, p3];
};

